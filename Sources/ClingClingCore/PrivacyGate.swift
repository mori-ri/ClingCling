import Foundation

/// Privacy Gate の設定値（UI の Settings から渡される）
public struct PrivacySettings: Sendable {
    /// Secret を検出した Item をディスクに保存しない（メモリ上で一時保持のみ）
    public var neverSavePasswords: Bool
    /// 認証コードをディスクに保存しない（メモリ上で一時保持のみ）
    public var neverSaveVerificationCodes: Bool
    /// Password Manager からのコピーを一切キャプチャしない
    public var excludePasswordManagers: Bool
    /// 一時保持の有効期間
    public var temporaryLifetime: TimeInterval
    /// アプリ単位のポリシー（bundle ID → policy）
    public var appPolicies: [String: AppCapturePolicy]

    public init(
        neverSavePasswords: Bool = true,
        neverSaveVerificationCodes: Bool = true,
        excludePasswordManagers: Bool = true,
        temporaryLifetime: TimeInterval = 5 * 60,
        appPolicies: [String: AppCapturePolicy] = [:]
    ) {
        self.neverSavePasswords = neverSavePasswords
        self.neverSaveVerificationCodes = neverSaveVerificationCodes
        self.excludePasswordManagers = excludePasswordManagers
        self.temporaryLifetime = temporaryLifetime
        self.appPolicies = appPolicies
    }
}

/// Pasteboard から得た画像（PNG に変換済み）
public struct ImageCapture: Sendable {
    public var png: Data
    public var width: Int
    public var height: Int
    /// Vision で読み取った文字（OCR）。文字が写っていなければ空
    public var recognizedText: String

    public init(png: Data, width: Int, height: Int, recognizedText: String = "") {
        self.png = png
        self.width = width
        self.height = height
        self.recognizedText = recognizedText
    }
}

/// Pasteboard から得たキャプチャ候補
public struct CaptureInput: Sendable {
    /// 画像のときは空
    public var text: String
    /// 画像のときだけ値がある
    public var image: ImageCapture?
    /// NSPasteboard の type 識別子（`org.nspasteboard.ConcealedType` などの判定に使う）
    public var pasteboardTypes: Set<String>
    public var source: SourceApp
    public var date: Date

    public init(text: String, pasteboardTypes: Set<String>, source: SourceApp, date: Date = Date()) {
        self.text = text
        self.image = nil
        self.pasteboardTypes = pasteboardTypes
        self.source = source
        self.date = date
    }

    public init(image: ImageCapture, pasteboardTypes: Set<String>, source: SourceApp, date: Date = Date()) {
        self.text = ""
        self.image = image
        self.pasteboardTypes = pasteboardTypes
        self.source = source
        self.date = date
    }
}

public enum GateDecision: Sendable, Equatable {
    /// キャプチャしない（理由付き）
    case drop(reason: String)
    case capture(ClipItem)
}

/// Clipboard 処理の最前段。完全にローカルで動作する。
///
/// 原則: 「Secret だと判定したら止める」のではなく
/// 「安全だと判断できたものだけ外部送信可能にする」（Fail Closed）。
public struct PrivacyGate: Sendable {
    public static let concealedType = "org.nspasteboard.ConcealedType"
    public static let transientType = "org.nspasteboard.TransientType"
    public static let autoGeneratedType = "org.nspasteboard.AutoGeneratedType"
    /// 1Password 等が独自に付与する marker
    static let passwordManagerMarkers: Set<String> = [
        "com.agilebits.onepassword",
        "org.keepassxc.keepassxc.secret",
    ]

    public static let passwordManagerBundleIDs: Set<String> = [
        "com.1password.1password",
        "com.agilebits.onepassword7",
        "com.agilebits.onepassword-osx",
        "com.agilebits.onepassword4",
        "com.bitwarden.desktop",
        "com.apple.Passwords",
        "com.apple.keychainaccess",
        "org.keepassxc.keepassxc",
        "com.keepassium.KeePassium",
        "com.markmcguill.strongbox.mac",
        "com.lastpass.LastPass",
        "com.dashlane.dashlanephonefinal",
        "in.sinew.Enpass-Desktop",
        "com.proton.pass",
        "me.proton.pass.electron",
    ]

    /// 外部送信の候補にしてよい分類。ここに無い分類（other / credential など）は常に Local Only。
    static let externallyEligibleTypes: Set<ContentType> = [.text, .url, .code, .command, .error, .json]

    /// 外部送信を許可する最大長（巨大なペーストの誤送信を防ぐ）
    static let maxExternalLength = 20_000

    let detector: SecretDetector
    let classifier: ContentClassifier

    public init(detector: SecretDetector = SecretDetector(), classifier: ContentClassifier = ContentClassifier()) {
        self.detector = detector
        self.classifier = classifier
    }

    public func evaluate(_ input: CaptureInput, settings: PrivacySettings) -> GateDecision {
        if let image = input.image {
            return evaluateImage(image, input: input, settings: settings)
        }
        let text = input.text
        guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else {
            return .drop(reason: "empty")
        }

        // 1–2. Pasteboard metadata / Source Application
        if let drop = precheck(input, settings: settings) { return drop }
        let policy = Self.policy(for: input.source, settings: settings)

        // 3. Secret Detection（正規表現 + エントロピー）
        let findings = detector.scan(text)
        var (sensitivity, reasons) = Self.sensitivity(of: findings)

        // 4. Content Classification
        var type = classifier.classify(text)
        if type == .verificationCode {
            sensitivity = .secret
            reasons.append("Verification Code")
        } else if sensitivity >= .suspicious, Self.isMostlySecret(text, findings: findings), type != .url {
            // 本文のほとんどが Token そのものなら credential として扱う
            type = .credential
        }

        // 5. 外部送信可否（許可リスト方式）
        var externalAllowed = sensitivity == .normal
            && Self.externallyEligibleTypes.contains(type)
            && text.count <= Self.maxExternalLength
        if policy == .localOnly {
            externalAllowed = false
            reasons.append("App policy: Local only")
        }

        // 6. Retention
        let temporary = (type == .verificationCode && settings.neverSaveVerificationCodes)
            || (type != .verificationCode && sensitivity == .secret && settings.neverSavePasswords)
        let retention: Retention = temporary ? .temporary : .normal

        let item = ClipItem(
            createdAt: input.date,
            content: text,
            contentHash: ContentHash.sha256(text),
            contentType: type,
            source: input.source,
            sensitivity: sensitivity,
            retention: retention,
            externalAllowed: externalAllowed,
            expiresAt: temporary ? input.date.addingTimeInterval(settings.temporaryLifetime) : nil,
            reasons: reasons
        )
        return .capture(item)
    }

    /// 画像は写っている文字だけを検査する（OCR はアプリ側で Vision が行い、`recognizedText` で渡される）。
    /// 文字以外の中身や OCR の読み違いまでは検査できないので、保存はしても外部送信は常に不可（Fail Closed）。
    /// 読み取った文字に Secret・認証コードがあれば、テキストと同じくディスクに書かない一時 Item にする。
    func evaluateImage(_ image: ImageCapture, input: CaptureInput, settings: PrivacySettings) -> GateDecision {
        guard !image.png.isEmpty, image.width > 0, image.height > 0 else { return .drop(reason: "empty") }
        if let drop = precheck(input, settings: settings) { return drop }
        let policy = Self.policy(for: input.source, settings: settings)

        let text = image.recognizedText.trimmingCharacters(in: .whitespacesAndNewlines)
        var sensitivity: Sensitivity = .normal
        var reasons: [String]
        var isVerificationCode = false
        if text.isEmpty {
            reasons = ["Image: content not inspected"]
        } else {
            let scanned = Self.sensitivity(of: detector.scan(text))
            sensitivity = scanned.sensitivity
            reasons = ["Image: text recognized"] + scanned.reasons
            if classifier.classify(text) == .verificationCode {
                isVerificationCode = true
                sensitivity = .secret
                reasons.append("Verification Code")
            }
        }
        if policy == .localOnly { reasons.append("App policy: Local only") }

        let temporary = (isVerificationCode && settings.neverSaveVerificationCodes)
            || (!isVerificationCode && sensitivity == .secret && settings.neverSavePasswords)
        let hash = ContentHash.sha256(image.png)
        return .capture(ClipItem(
            createdAt: input.date,
            content: String(localized: "画像 \(image.width)×\(image.height)"),
            contentHash: hash,
            contentType: .image,
            source: input.source,
            sensitivity: sensitivity,
            retention: temporary ? .temporary : .normal,
            externalAllowed: false,
            expiresAt: temporary ? input.date.addingTimeInterval(settings.temporaryLifetime) : nil,
            reasons: reasons,
            image: ClipImage(fileName: hash + ".png", width: image.width, height: image.height, text: text)
        ))
    }

    /// 検出結果から機密度と判定理由（規則名、重複なし）をまとめる
    static func sensitivity(of findings: [SecretFinding]) -> (sensitivity: Sensitivity, reasons: [String]) {
        var reasons: [String] = []
        var sensitivity: Sensitivity = .normal
        for finding in findings {
            let level: Sensitivity = switch finding.kind {
            case .knownSecret: .secret
            case .highEntropy: .suspicious
            case .personal: .personal
            }
            sensitivity = max(sensitivity, level)
            if !reasons.contains(finding.rule) { reasons.append(finding.rule) }
        }
        return (sensitivity, reasons)
    }

    /// Pasteboard metadata（nspasteboard.org の慣習）とコピー元アプリの判定。キャプチャしないなら drop を返す。
    private func precheck(_ input: CaptureInput, settings: PrivacySettings) -> GateDecision? {
        if input.pasteboardTypes.contains(Self.concealedType) {
            return .drop(reason: "concealed pasteboard marker")
        }
        if input.pasteboardTypes.contains(Self.transientType) || input.pasteboardTypes.contains(Self.autoGeneratedType) {
            return .drop(reason: "transient pasteboard marker")
        }
        if !input.pasteboardTypes.isDisjoint(with: Self.passwordManagerMarkers) {
            return .drop(reason: "password manager marker")
        }
        if Self.policy(for: input.source, settings: settings) == .neverCapture {
            return .drop(reason: "app policy: never capture")
        }
        if settings.excludePasswordManagers, Self.isPasswordManager(input.source) {
            return .drop(reason: "password manager")
        }
        return nil
    }

    static func policy(for source: SourceApp, settings: PrivacySettings) -> AppCapturePolicy {
        source.bundleID.flatMap { settings.appPolicies[$0] } ?? .capture
    }

    public static func isPasswordManager(_ app: SourceApp) -> Bool {
        if let id = app.bundleID, passwordManagerBundleIDs.contains(id) { return true }
        let name = (app.name ?? "").lowercased()
        return ["1password", "bitwarden", "keepass", "lastpass", "dashlane", "enpass", "strongbox", "proton pass"]
            .contains { name.contains($0) } || name == "passwords"
    }

    /// Secret 部分が本文（空白除く）の大半を占めるか
    static func isMostlySecret(_ text: String, findings: [SecretFinding]) -> Bool {
        let total = text.filter { !$0.isWhitespace }.count
        guard total > 0 else { return false }
        let secretChars = findings
            .filter { $0.kind != .personal }
            .reduce(0) { $0 + text[$1.range].filter { !$0.isWhitespace }.count }
        return Double(secretChars) / Double(total) >= 0.6
    }
}
